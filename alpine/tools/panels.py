"""Original data-panel geometry shared by Monkey C and the design contact sheet.

Coordinates are logical native pixels (176 mono / 260 colour); text stays separate.
Each ornament belongs to a slot, so hiding a field also removes its decoration.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def layout(mono, style):
    xs = [46, 88, 130] if mono else [79, 130, 181]
    y, w, h, bottom = (139, 39, 11, 165) if mono else (204, 47, 15, 242)
    groups = []
    for i, x in enumerate(xs):
        # Explicit integer edges keep odd-width cards symmetrical on 1-bit screens.
        l, r = x - w // 2, x + w // 2
        ops = []
        def line(*v): ops.append(('line', v))
        def poly(*v): ops.append(('poly', v))
        def rect(*v): ops.append(('rect', v))
        if style in (0, 1):
            rect(l, y, w, h)
        elif style == 2:
            # Open, cut-corner card with a fine separator; label uses accent ink.
            points = [(l+3,y),(r-3,y),(r,y+3),(r,bottom-3),
                      (r-3,bottom),(l+3,bottom),(l,bottom-3),(l,y+3),(l+3,y)]
            for a,b in zip(points,points[1:]): line(*a,*b)
            line(l+4,y+h,r-4,y+h)
        else:
            poly((l+2,y),(r,y),(r,y+h-3),(r-3,y+h-1),(l,y+h-1),(l,y+2))
            # Disconnected lower brackets leave space around the value.
            line(l,bottom-3,l,bottom);line(l,bottom,l+6,bottom)
            line(r-6,bottom,r,bottom);line(r,bottom,r,bottom-3)
        if style == 1 and i in (0,2):
            # Three tapering wings, with two black gaps: recognisable at 1x.
            edge = l-2 if i==0 else r+2
            direction = -1 if i==0 else 1
            for row in range(3):
                yy=y+row*(4 if mono else 5);length=(11 if mono else 19)-row*2
                poly((edge,yy),(edge+direction*length,yy),
                     (edge+direction*(length-1),yy+2),(edge,yy+2))
        if style == 3 and i in (0,2):
            edge = l-3 if i==0 else r+3;direction = -1 if i==0 else 1
            for row in range(3):
                xx=edge+direction*row*3
                line(xx,y+2,xx+direction*2,y+h-3)
        groups.append(ops)
    return groups


def generate(dest, mono):
    out = ['// Generated by tools/panels.py. Do not edit.', 'import Toybox.Lang;', 'import Toybox.Graphics;', 'module PanelDecor {',
           ' function draw(face as AlpineView,dc as Graphics.Dc,style as Number,active as Array<Boolean>,accent as Number) {']
    for selected in (mono,):
        out.append('   switch(style) {')
        for style in range(4):
            out.append(f'    case {style}:')
            for i, ops in enumerate(layout(mono,style)):
                out.append(f'     if(active[{i}]) {{')
                for kind,args in ops:
                    coords=('['+','.join('['+','.join(map(str,p))+']' for p in args)+']') if kind=='poly' else ','.join(map(str,args))
                    out.append(f'      face.{kind}(dc,{coords},accent);')
                out.append('     }')
            out.append('     break;')
        out.append('   }')
    out.extend([' }','}'])
    (dest/'PanelDecor.mc').write_text('\n'.join(out)+'\n')


