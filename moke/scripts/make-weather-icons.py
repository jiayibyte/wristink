"""Generate original 15px monochrome weather glyphs and a source-derived gallery."""
from pathlib import Path
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
NAMES = ['暂无数据', '晴天', '多云', '阴天', '下雨', '下雪', '雷雨', '雨夹雪', '雾霾', '大风', '冰雹']


def glyph(kind):
    if kind==0:
        unknown=Image.new('L',(15,15));ImageDraw.Draw(unknown).line((4,7,10,7),fill=255)
        return unknown
    ss=8
    im=Image.new('L',(15*ss,15*ss))
    canvas=ImageDraw.Draw(im)
    class Pen:
        def line(self,points,fill=1,**kwargs):
            if len(points)==4 and not isinstance(points[0],tuple):points=[points[:2],points[2:]]
            canvas.line([(round((x+.5)*ss),round((y+.5)*ss)) for x,y in points],fill=255 if fill else 0,width=ss,joint='curve')
        def ellipse(self,box,fill=None,outline=None):
            scaled=(box[0]*ss,box[1]*ss,(box[2]+1)*ss-1,(box[3]+1)*ss-1)
            canvas.ellipse(scaled,fill=None if fill is None else (255 if fill else 0),outline=None if outline is None else (255 if outline else 0),width=ss)
        def rectangle(self,box,fill=None,outline=None):
            scaled=(box[0]*ss,box[1]*ss,(box[2]+1)*ss-1,(box[3]+1)*ss-1)
            canvas.rectangle(scaled,fill=None if fill is None else (255 if fill else 0),outline=None if outline is None else (255 if outline else 0),width=ss)
    d=Pen()
    def cloud(y=0):
        # The same 15px box, with continuous lobe curves and a level base.
        shift=y+2;points=[(2.8,8.4+shift)]
        for a,b,c,e in [((2.8,8.4),(.9,8.4),(.5,7.5),(.5,6.1)),
                        ((.5,6.1),(.5,4.6),(2.4,3.6),(4.0,4.4)),
                        ((4.0,4.4),(4.4,2.0),(5.8,.6),(8.0,.6)),
                        ((8.0,.6),(10.2,.6),(11.6,2.0),(11.8,3.7)),
                        ((11.8,3.7),(13.7,3.7),(14.4,4.8),(14.4,6.2)),
                        ((14.4,6.2),(14.4,7.7),(13.2,8.4),(12.1,8.4))]:
            for i in range(1,25):
                t=i/24;points.append(((1-t)**3*a[0]+3*(1-t)**2*t*b[0]+3*(1-t)*t*t*c[0]+t**3*e[0],(1-t)**3*a[1]+3*(1-t)**2*t*b[1]+3*(1-t)*t*t*c[1]+t**3*e[1]+shift))
        points.append(points[0]);xy=[(round(x*ss),round(y*ss)) for x,y in points]
        canvas.polygon(xy,fill=0);canvas.line(xy,fill=255,width=ss,joint='curve')
    def flake(x,y):
        d.line((x,y-2,x,y+2),fill=1)
        d.line((x-2,y-1,x+2,y+1),fill=1);d.line((x-2,y+1,x+2,y-1),fill=1)
    if kind == 0:
        d.line((4,7,10,7),fill=1)
    elif kind == 1:
        d.ellipse((4,4,10,10),outline=1)
        for line in ((7,0,7,2),(7,12,7,14),(0,7,2,7),(12,7,14,7),
                     (2,2,3,3),(11,11,12,12),(2,12,3,11),(11,3,12,2)):
            d.line(line,fill=1)
    elif kind == 2:
        d.ellipse((7,2,13,8),outline=1)
        for line in ((10,0,10,1),(14,4,14,5),(5,1,6,2)):
            d.line(line,fill=1)
        cloud(2)
    elif kind == 3:
        cloud(1)
    elif kind in (4,5,6,7,10):
        cloud(-2)
        if kind == 4:
            for x in (3,7,11):
                canvas.rounded_rectangle((x*ss,10*ss,(x+1)*ss-1,14*ss-1),radius=ss/2,fill=255)
        elif kind == 5:
            flake(3,12);flake(10,12)
        elif kind == 6:
            d.line([(8,8),(5,11),(8,11),(6,14),(11,10),(8,10),(10,8)],fill=1)
            d.line((2,10,1,12),fill=1)
        elif kind == 7:
            d.line((3,10,2,13),fill=1);flake(10,12)
        else:
            d.rectangle((2,10,4,12),outline=1);d.rectangle((9,11,11,13),outline=1)
    elif kind == 8:
        cloud(-2)
        d.line((0,10,10,10),fill=1);d.line((4,12,14,12),fill=1);d.line((0,14,9,14),fill=1)
    elif kind == 9:
        d.line([(1,4),(10,4),(12,3),(12,1),(10,0),(8,1)],fill=1)
        d.line([(0,7),(12,7),(14,6),(14,4),(13,3)],fill=1)
        d.line([(2,10),(9,10),(11,11),(11,13),(9,14),(7,13)],fill=1)
    return im.resize((15,15),Image.Resampling.BOX).point(lambda p:255 if p>=120 else 0)


if __name__ == '__main__':
    icons = [glyph(i) for i in range(len(NAMES))]
    assert len({im.tobytes() for im in icons}) == len(NAMES)
    rows = [[sum((1 << x) for x in range(15) if im.getpixel((x,y))) for y in range(15)] for im in icons]
    # The 60 KB device only needs the selected glyph, not 11 resident number arrays.
    source='// Original pixel glyphs, generated by scripts/make-weather-icons.py.\nimport Toybox.Lang;\nmodule WeatherGlyphs {\n    function pixels(kind) as Array<Number> {switch(kind){\n'
    for i,pixels in enumerate(rows):
        source+=f'        case {i}:return {json.dumps(pixels)};\n'
    source+='    }return pixels(0);}\n}\n'
    (ROOT/'source/WeatherGlyphs.mc').write_text(source)
    # This sheet renders the exact pixel rows consumed by the watch, enlarged 4x.
    board = Image.new('RGB',(792,268),'#e9e9e6')
    d = ImageDraw.Draw(board)
    font = ImageFont.truetype('/System/Library/Fonts/STHeiti Medium.ttc',15,index=1)
    for dark in (True,False):
        y=0 if dark else 112
        bg,fg = ('black','white') if dark else ('white','black')
        d.rectangle((0,y,791,y+111),fill=bg)
        for i,im in enumerate(icons):
            tile=Image.new('RGB',(15,15),bg);tile.paste(fg,(0,0),im.convert('L'))
            board.paste(tile.resize((60,60),Image.Resampling.NEAREST),(i*72+6,y+9))
            d.text((i*72+36,y+78),NAMES[i],font=font,fill=fg,anchor='mm')
    d.text((12,241),'源码像素图标预览；随佳明天气状态自动切换。',font=font,fill='#444')
    board.save(ROOT/'bin/weather-icons.png')
    print('Generated 11 distinct 15 x 15 weather icons and both-theme gallery.')
